/**
 * What naming the callee that lies outside the indexed corpus changed on the
 * ten evidence corpora: the failure taxonomy before and after, and the three
 * figures that must not move.
 *
 * This relabels failures and resolves nothing, so `resolved`, the call-edge
 * fingerprint and the raw-entry-point fingerprint are the same on both arms
 * and only `by_reason` differs. The control arm is the tree the step started
 * from (0dceea99), not the tree `RECORDED_CORPUS_RESOLUTION` was measured on
 * (038b7daa): later steps moved those rows' resolved counts, so an unchanged
 * check against them would measure those steps instead of this one. Both arms
 * ran `run_load_benchmark.ts --baseline` over the same corpus commits and
 * predicates as `RECORDED_CORPUS_RESOLUTION`, on one box in one sitting.
 *
 * What the two new columns account for is the callee a language or an unindexed
 * module defines: the Rust prelude (`Some`, `Ok`, `Err`), the Python builtins,
 * the JavaScript host globals (`console`, `JSON`, `require`), and any import
 * whose module names no indexed file (`os`, `numpy`, `fs`, `std`). A test
 * framework's own words (Jasmine's `expect` and `it`, mocha's `describe`) are
 * bound by no declaration and no import, and the language does not define
 * them, so they stay in `name_not_in_scope`; a `self` receiver whose base class
 * is an unindexed import (django's `assertEqual`) stays in `method_not_on_type`.
 */

